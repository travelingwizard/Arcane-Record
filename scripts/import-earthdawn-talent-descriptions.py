#!/usr/bin/env python3
"""Generate deterministic Earthdawn talent descriptions from the supplied workbook."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from openpyxl import load_workbook


EXPECTED_HEADERS = ["Talent Name", "Description", "Discipline", "Source"]
EXPECTED_ROWS = 244


def text(value: object) -> str:
    return "" if value is None else str(value).strip()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    workbook = load_workbook(args.input, read_only=True, data_only=True)
    sheet = workbook["Table 1"]
    iterator = sheet.iter_rows(values_only=True)
    headers = [text(value) for value in next(iterator)]
    if headers != EXPECTED_HEADERS:
        raise ValueError(f"Unexpected headers: {headers!r}")

    records: list[tuple[str, str, str, str]] = []
    for values in iterator:
        if not any(text(value) for value in values):
            continue
        name, description, discipline, source = map(text, values)
        if not name or not description:
            raise ValueError(f"Talent name and description are required: {values!r}")
        records.append((name, description, discipline, source))

    if len(records) != EXPECTED_ROWS:
        raise ValueError(f"Expected {EXPECTED_ROWS} rows, found {len(records)}")
    normalized = [name.casefold() for name, *_ in records]
    duplicates = sorted({name for name in normalized if normalized.count(name) > 1})
    if duplicates:
        raise ValueError(f"Duplicate talent names: {duplicates}")

    lines = [
        "// Generated by scripts/import-earthdawn-talent-descriptions.py. Do not edit by hand.",
        "export type EarthdawnTalentDescriptionRow = readonly [name: string, description: string, disciplineText: string, sourceReferences: string];",
        "",
        "export const earthdawnTalentDescriptionRows: ReadonlyArray<EarthdawnTalentDescriptionRow> = [",
    ]
    for record in records:
        values = ", ".join(json.dumps(value, ensure_ascii=False) for value in record)
        lines.append(f"  [{values}],")
    lines += ["] as const;", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
