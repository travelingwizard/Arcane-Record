#!/usr/bin/env python3
"""Generate deterministic Earthdawn reference data from supplied workbooks."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

from openpyxl import load_workbook


TALENT_SOURCES = {
    1: "ed4.players-guide", 2: "ed4.deeper-secrets", 3: "ed4.gamemasters-guide",
    4: "ed4.companion", 5: "ed4.mystic-paths", 6: "ed4.grand-bazaar",
    7: "ed4.elven-nations", 8: "ed4.iopos", 9: "ed4.vasgothia",
    10: "ed4.travar", 11: "ed4.questors",
}
SKILL_SOURCES = {
    1: "ed4.elven-nations", 2: "ed4.deeper-secrets", 3: "ed4.players-guide",
    4: "ed4.iopos", 5: "ed4.questors", 6: "ed4.companion",
    7: "ed4.gamemasters-guide", 8: "ed4.mystic-paths",
}
THREAD_SOURCES = {
    1: "ed4.companion", 2: "ed4.elven-nations", 3: "ed4.iopos",
    4: "ed4.gamemasters-guide", 5: "ed4.mystic-paths", 6: "ed4.deeper-secrets",
    7: "ed4.vasgothia", 8: "ed4.grand-bazaar", 9: "ed4.travar",
    10: "ed4.questors", 11: "ed4.players-guide",
}


def text(value: object) -> str:
    return "" if value is None else str(value).strip()


def source_number(value: object) -> int:
    match = re.search(r"\d+", text(value))
    if not match:
        raise ValueError(f"Invalid source reference: {value!r}")
    return int(match.group())


def page(value: object) -> int | None:
    if value is None or text(value) == "":
        return None
    match = re.search(r"\d+", text(value))
    if not match:
        raise ValueError(f"Invalid page: {value!r}")
    return int(match.group())


def rows(path: Path) -> list[dict[str, object]]:
    sheet = load_workbook(path, read_only=True, data_only=True).active
    iterator = sheet.iter_rows(values_only=True)
    headers = [text(value) for value in next(iterator)]
    result = []
    for values in iterator:
        record = dict(zip(headers, values))
        if any(text(value) for value in values):
            result.append(record)
    return result


def ts(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def assert_unique(records: list[dict[str, object]], field: str, expected: int) -> None:
    if len(records) != expected:
        raise ValueError(f"Expected {expected} rows, found {len(records)}")
    names = [text(record[field]).casefold() for record in records]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise ValueError(f"Duplicate {field} values: {duplicates}")


def write_output(talent_path: Path, skill_path: Path, thread_path: Path, output: Path) -> None:
    talents = rows(talent_path)
    skills = rows(skill_path)
    threads = rows(thread_path)
    assert_unique(talents, "Talent Name", 318)
    assert_unique(skills, "Skill Name", 65)
    assert_unique(threads, "Item Name", 138)

    lines = [
        "// Generated by scripts/import-earthdawn-reference-workbooks.py. Do not edit by hand.",
        "export type EarthdawnTalentSupplementRow = readonly [name: string, description: string, requirements: string, sourceId: string, page: number | null];",
        "export type EarthdawnSkillReferenceRow = readonly [name: string, category: 'general' | 'knowledge' | 'artisan' | 'language', description: string, sourceId: string, page: number | null];",
        "export type EarthdawnThreadItemReferenceRow = readonly [name: string, itemType: string, description: string, inferredKeyKnowledge: string, sourceId: string, page: number | null];",
        "",
        "export const earthdawnTalentSupplementRows: ReadonlyArray<EarthdawnTalentSupplementRow> = [",
    ]
    for record in talents:
        source_id = TALENT_SOURCES.get(source_number(record["Source"]))
        if not source_id:
            raise ValueError(f"Unknown talent source: {record['Source']!r}")
        lines.append(f"  [{ts(text(record['Talent Name']))}, {ts(text(record['Description']))}, {ts(text(record['Game Terms/Requirements']))}, {ts(source_id)}, {ts(page(record['Page Number']))}],")
    lines += ["] as const;", "", "export const earthdawnSkillReferenceRows: ReadonlyArray<EarthdawnSkillReferenceRow> = ["]
    for record in skills:
        category = text(record["Skill Type"]).casefold()
        if category not in {"general", "knowledge", "artisan", "language"}:
            raise ValueError(f"Unknown skill category: {category!r}")
        source_id = SKILL_SOURCES.get(source_number(record["Source"]))
        if not source_id:
            raise ValueError(f"Unknown skill source: {record['Source']!r}")
        lines.append(f"  [{ts(text(record['Skill Name']))}, {ts(category)}, {ts(text(record['Description']))}, {ts(source_id)}, {ts(page(record['Page Number']))}],")
    lines += ["] as const;", "", "export const earthdawnThreadItemReferenceRows: ReadonlyArray<EarthdawnThreadItemReferenceRow> = ["]
    for record in threads:
        source_id = THREAD_SOURCES.get(source_number(record["Source"]))
        if not source_id:
            raise ValueError(f"Unknown thread item source: {record['Source']!r}")
        lines.append(f"  [{ts(text(record['Item Name']))}, {ts(text(record['Item Type']))}, {ts(text(record['Item Description']))}, {ts(text(record['Key Knowledge (Inferred)']))}, {ts(source_id)}, {ts(page(record['Page Number']))}],")
    lines += ["] as const;", ""]
    output.write_text("\n".join(lines), encoding="utf-8")
    prettier_candidates = [
        Path.cwd() / "node_modules/.bin/prettier",
        Path.cwd().parents[1] / "node_modules/.bin/prettier",
    ]
    prettier = next((candidate for candidate in prettier_candidates if candidate.exists()), None)
    if prettier:
        subprocess.run(
            [
                str(prettier),
                "--config",
                str(Path.cwd() / ".prettierrc.json"),
                "--ignore-path",
                "/dev/null",
                "--write",
                str(output),
            ],
            check=True,
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--talents", type=Path, required=True)
    parser.add_argument("--skills", type=Path, required=True)
    parser.add_argument("--thread-items", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write_output(args.talents, args.skills, args.thread_items, args.output)


if __name__ == "__main__":
    main()
