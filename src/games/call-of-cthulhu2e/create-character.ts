import { skills } from './catalog';
import {
  COC2E_SCHEMA_VERSION,
  investigatorGroupIds,
  keeperGroupIds,
} from './definitions';
import type { Coc2eInvestigator, Coc2eKeeper } from './schema';
const citeSkill = (x: (typeof skills)[number]) => ({
  id: crypto.randomUUID(),
  definitionId: x.id,
  name: x.name,
  sourceId: x.sourceId,
  page: x.page,
  notes: x.summary,
  custom: false,
  rating: x.id.endsWith('own-language')
    ? 0
    : Number(x.summary.match(/Base chance (\d+)%/)?.[1] ?? 0),
  baseChance: Number(x.summary.match(/Base chance (\d+)%/)?.[1] ?? 0),
  occupationPoints: 0,
  personalPoints: 0,
  experienceChecked: false,
  specialty: '',
  origin: 'catalog' as const,
});
export function createCoc2eInvestigator(
  status: Coc2eInvestigator['creation']['status'] = 'draft',
): Coc2eInvestigator {
  return {
    schemaVersion: COC2E_SCHEMA_VERSION,
    name: '',
    player: '',
    sex: '',
    age: 20,
    nationality: '',
    residence: '',
    era: '1920s',
    concept: '',
    occupationName: '',
    mode: 'build',
    layout: {
      build: [...investigatorGroupIds],
      play: [
        'investigation',
        'resources',
        'sanity',
        'skills',
        'combat',
        'equipment',
        'characteristics',
        'advancement',
        'investigator',
        'records',
      ],
    },
    enabledSources: ['coc2e.core'],
    showUnavailable: false,
    creation: {
      status,
      step: 1,
      occupationId: '',
      occupationPointsSpent: 0,
      personalPointsSpent: 0,
      previousExperience: false,
      rolls: [],
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    characteristics: {
      str: 0,
      con: 0,
      siz: 0,
      dex: 0,
      app: 0,
      int: 0,
      pow: 0,
      edu: 0,
    },
    resources: {
      sanityCurrent: 0,
      sanityMaximum: 99,
      magicPoints: 0,
      hitPoints: 0,
      temporaryInsanity: false,
      indefiniteInsanity: false,
      insanityDescription: '',
      injuries: [],
    },
    skills: skills.filter((x) => x.sourceId === 'coc2e.core').map(citeSkill),
    weapons: [],
    equipment: [],
    spells: [],
    tomes: [],
    mythosDiscoveries: [],
    clues: [],
    contacts: [],
    income: '',
    savings: '',
    schools: '',
    degrees: '',
    historyText: '',
    notes: '',
    totalExperience: 0,
    currentExperience: 0,
    rollHistory: [],
    history: [],
    campaign: { kind: 'none', snapshot: null },
  };
}
export function createCoc2eKeeper(
  status: Coc2eKeeper['creation']['status'] = 'draft',
): Coc2eKeeper {
  return {
    schemaVersion: COC2E_SCHEMA_VERSION,
    name: '',
    keeper: '',
    era: '1920s',
    mode: 'build',
    layout: {
      build: [...keeperGroupIds],
      play: [
        'investigations',
        'clues',
        'roster',
        'mythos',
        'sessions',
        'campaign',
        'records',
      ],
    },
    enabledSources: ['coc2e.core'],
    showUnavailable: false,
    revision: 0,
    creation: {
      status,
      step: 1,
      occupationId: '',
      occupationPointsSpent: 0,
      personalPointsSpent: 0,
      previousExperience: false,
      rolls: [],
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    roster: [],
    investigations: [],
    mythos: [],
    sessions: [],
    history: [],
    privateNotes: '',
  };
}
