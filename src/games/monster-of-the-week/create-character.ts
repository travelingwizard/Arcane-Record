import { basicMoves } from './catalog';
import {
  MOTW_SCHEMA_VERSION,
  hunterGroupIds,
  keeperGroupIds,
} from './definitions';
import type { MotwHunter, MotwKeeper } from './schema';
const cite = (x: (typeof basicMoves)[number]) => ({
  id: crypto.randomUUID(),
  definitionId: x.id,
  name: x.name,
  sourceId: x.sourceId,
  page: x.page,
  notes: x.summary,
  custom: false,
});
export function createMotwHunter(
  status: MotwHunter['creation']['status'] = 'draft',
): MotwHunter {
  return {
    schemaVersion: MOTW_SCHEMA_VERSION,
    name: '',
    player: '',
    pronouns: '',
    look: '',
    concept: '',
    playbookId: '',
    teamConceptId: '',
    customTeamConcept: '',
    mode: 'build',
    layout: {
      build: [...hunterGroupIds],
      play: [
        'mystery',
        'harm',
        'luck',
        'moves',
        'playbook',
        'gear',
        'ratings',
        'team',
        'advancement',
        'hunter',
        'records',
      ],
    },
    enabledSources: ['motw.core'],
    showUnavailable: false,
    creation: {
      status,
      step: 1,
      ratingPackageIndex: null,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    ratings: { charm: 0, cool: 0, sharp: 0, tough: 0, weird: 0 },
    moves: basicMoves.map((x) => ({
      ...cite(x),
      state: 'available',
      origin: 'creation',
    })),
    playbookFeatures: [],
    gear: [],
    histories: [],
    luck: { current: 7, maximum: 7, special: '' },
    harm: { current: 0, unstable: false, armor: 0, notes: '' },
    experienceMarks: 0,
    levelUps: 0,
    improvements: [],
    advancedMoves: [],
    retired: false,
    mystery: {
      name: '',
      clues: [],
      questions: [],
      holds: 0,
      temporaryEffects: [],
      notes: '',
    },
    rollHistory: [],
    history: [],
    notes: '',
    campaign: { kind: 'none', snapshot: null },
  };
}
export function createMotwKeeper(
  status: MotwKeeper['creation']['status'] = 'draft',
): MotwKeeper {
  return {
    schemaVersion: MOTW_SCHEMA_VERSION,
    name: '',
    keeper: '',
    teamConcept: '',
    mode: 'build',
    layout: {
      build: [...keeperGroupIds],
      play: [
        'mysteries',
        'threats',
        'session',
        'roster',
        'arcs',
        'campaign',
        'records',
      ],
    },
    enabledSources: ['motw.core'],
    showUnavailable: false,
    revision: 0,
    creation: {
      status,
      step: 1,
      ratingPackageIndex: null,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    roster: [],
    mysteries: [],
    threats: [],
    arcs: [],
    customMoves: [],
    session: {
      title: '',
      date: '',
      notes: '',
      answers: [false, false, false, false],
      awardsReviewed: false,
    },
    history: [],
    notes: '',
  };
}
