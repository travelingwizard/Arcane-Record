import { actions, standardItems } from './catalog';
import {
  BITD_SCHEMA_VERSION,
  characterGroupIds,
  crewGroupIds,
} from './definitions';
import type { BitdCharacter, BitdCrew } from './schema';
const cite = (x: {
  id: string;
  name: string;
  sourceId: string;
  page: number;
  summary: string;
}) => ({
  definitionId: x.id,
  name: x.name,
  sourceId: x.sourceId,
  page: x.page,
  notes: x.summary,
});
export function createBitdCharacter(
  status: BitdCharacter['creation']['status'] = 'draft',
): BitdCharacter {
  return {
    schemaVersion: BITD_SCHEMA_VERSION,
    name: '',
    player: '',
    alias: '',
    look: '',
    heritageId: '',
    backgroundId: '',
    playbookId: '',
    mode: 'build',
    layout: {
      build: [...characterGroupIds],
      play: [
        'score',
        'stress',
        'harm',
        'loadout',
        'actions',
        'abilities',
        'vice',
        'downtime',
        'advancement',
        'relationships',
        'character',
        'records',
      ],
    },
    enabledSources: ['bitd.core'],
    creation: {
      status,
      step: 1,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    actions: actions.map((x) => ({ ...cite(x), rating: 0, xp: 0 })),
    abilities: [],
    vice: { typeId: '', purveyor: '', notes: '' },
    friend: '',
    rival: '',
    stress: 0,
    trauma: [],
    harm: [],
    healing: 0,
    armor: { normal: false, heavy: false, special: false },
    load: 'normal',
    items: standardItems.map((x) => ({
      ...cite(x),
      load: 1,
      state: 'available',
    })),
    coin: 0,
    stash: 0,
    score: {
      plan: '',
      detail: '',
      target: '',
      position: 'risky',
      effect: 'standard',
      notes: '',
    },
    downtime: [],
    projects: [],
    xp: { playbook: 0, insight: 0, prowess: 0, resolve: 0 },
    retirement: '',
    rollHistory: [],
    history: [],
    notes: '',
    crew: { kind: 'none' },
  };
}
export function createBitdCrew(
  status: BitdCrew['creation']['status'] = 'draft',
): BitdCrew {
  return {
    schemaVersion: BITD_SCHEMA_VERSION,
    name: '',
    gm: '',
    typeId: '',
    reputationId: '',
    lair: '',
    huntingGrounds: '',
    mode: 'build',
    layout: {
      build: [...crewGroupIds],
      play: [
        'scores',
        'heat',
        'coin',
        'downtime',
        'cohorts',
        'factions',
        'clocks',
        'crew',
        'reputation',
        'abilities',
        'claims',
        'history',
        'gm',
        'records',
      ],
    },
    enabledSources: ['bitd.core'],
    showUnavailableSources: false,
    gmToolsEnabled: false,
    revision: 0,
    creation: {
      status,
      step: 1,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    abilities: [],
    upgrades: [],
    favoriteContact: '',
    contacts: [],
    cohorts: [],
    claims: [],
    factions: [],
    tier: 0,
    hold: 'strong',
    rep: 0,
    turf: 0,
    heat: 0,
    wanted: 0,
    coin: 2,
    vaults: 0,
    war: false,
    incarceration: [],
    scores: [],
    downtime: [],
    clocks: [],
    history: [],
    gmSavedPrompts: [],
    rollHistory: [],
    notes: '',
  };
}
