import type { CatalogCitation } from '../shared/catalog-sources';

export interface CurseCatalogDefinition extends CatalogCitation {
  id: string;
  name: string;
  kind: 'equipment' | 'edge' | 'spell';
  aliases: string[];
  summary: string;
  requirements: string[];
  dotCost: number | null;
  costVerified: boolean;
  automation: 'reference-only';
}

type ArenaAllocation = { mental: number; physical: number; social: number };
export interface CurseLineageDefinition extends CatalogCitation {
  id: 'dead' | 'hungry' | 'outcast' | 'primal' | 'sorcerer';
  name: string;
  summary: string;
  skills: readonly string[];
  skillChoices: 3;
  major: ArenaAllocation;
  minor: ArenaAllocation;
}
export interface CurseRoleDefinition extends CatalogCitation {
  id: string;
  name: string;
  summary: string;
  skills: readonly string[];
  skillChoice?: 'close-or-ranged-combat';
  attributes: ArenaAllocation;
}
export interface CurseFamilyDefinition extends CatalogCitation {
  id: string;
  name: string;
  lineage: CurseLineageDefinition['id'];
  summary: string;
  skills: readonly string[];
  skillChoices: 3;
  major: ArenaAllocation;
  minor: ArenaAllocation;
}

