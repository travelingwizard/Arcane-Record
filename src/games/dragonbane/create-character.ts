import { dragonbaneGroupIds } from './definitions';
import { dragonbaneSkills } from './catalog';
import { baseChance } from './rules';
import type { DragonbaneCharacter } from './schema';
export function createDragonbaneCharacter(
  status: DragonbaneCharacter['creation']['status'] = 'draft',
): DragonbaneCharacter {
  const attributes = { str: 10, con: 10, agl: 10, int: 10, wil: 10, cha: 10 };
  return {
    schemaVersion: 1,
    name: '',
    player: '',
    concept: '',
    appearance: '',
    nickname: '',
    kinId: '',
    professionId: '',
    age: 'adult',
    weakness: '',
    memento: '',
    mode: 'build',
    layout: {
      build: [...dragonbaneGroupIds],
      play: [
        'health',
        'conditions',
        'weapons',
        'abilities',
        'skills',
        'equipment',
        'adventure',
        'attributes',
        'advancement',
        'character',
        'records',
      ],
    },
    enabledSources: ['dragonbane.core'],
    showUnavailable: false,
    creation: {
      status,
      step: 1,
      attributeMethod: 'sequential',
      attributeRolls: [],
      swapped: false,
      professionalSkillIds: [],
      freeSkillIds: [],
      gearPackage: null,
      gearRoll: null,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    attributes,
    skills: dragonbaneSkills.map((x) => ({
      id: crypto.randomUUID(),
      definitionId: x.id,
      name: x.name,
      sourceId: x.sourceId,
      page: x.page,
      notes: '',
      custom: false,
      attribute: x.attribute,
      rating: baseChance(attributes[x.attribute]),
      trained: false,
      advancementMarked: false,
      teacherEligible: true,
      origin: 'creation',
    })),
    abilities: [],
    magic: {
      schoolId: null,
      grimoire: false,
      tricks: [],
      spells: [],
      mishaps: [],
    },
    resources: {
      hpCurrent: 10,
      hpMaximum: 10,
      wpCurrent: 10,
      wpMaximum: 10,
      gold: 0,
      silver: 0,
      copper: 0,
    },
    conditions: [],
    death: { successes: 0, failures: 0, rallied: false },
    rests: { roundUsed: false, stretchUsed: false },
    armor: { name: '', rating: 0, durability: 0, banes: [], active: false },
    helmet: { name: '', rating: 0, banes: [], active: false },
    weapons: [],
    inventory: [],
    tinyItems: [],
    mounts: [],
    temporaryEffects: [],
    injuries: [],
    ailments: [],
    adventure: { title: '', location: '', objective: '', notes: '' },
    advancement: [],
    rollHistory: [],
    history: [],
    notes: '',
    totalExperience: 0,
    currentExperience: 0,
  };
}
