import { factions } from './catalog';
import {
  ROOT_SCHEMA_VERSION,
  campaignGroupIds,
  vagabondGroupIds,
} from './definitions';
import type { RootCampaign, RootVagabond } from './schema';
export function createRootVagabond(
  status: RootVagabond['creation']['status'] = 'draft',
): RootVagabond {
  return {
    schemaVersion: ROOT_SCHEMA_VERSION,
    name: '',
    player: '',
    pronouns: '',
    species: '',
    look: '',
    demeanor: '',
    details: '',
    concept: '',
    playbookId: '',
    mode: 'build',
    layout: {
      build: [...vagabondGroupIds],
      play: [
        'jobs',
        'harm',
        'moves',
        'equipment',
        'reputation',
        'nature-drives',
        'feats',
        'connections',
        'stats',
        'advancement',
        'character',
        'records',
      ],
    },
    enabledSources: ['root.core'],
    showUnavailable: false,
    creation: {
      status,
      step: 1,
      statBoost: null,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    stats: { charm: 0, cunning: 0, finesse: 0, luck: 0, might: 0 },
    backgroundAnswers: [],
    nature: null,
    drives: [],
    moves: [],
    roguishFeats: [],
    weaponSkills: [],
    masteries: [],
    connections: [],
    reputation: factions
      .filter((x) => x.sourceId === 'root.core')
      .map((x) => ({
        id: crypto.randomUUID(),
        factionId: x.id,
        name: x.name,
        rating: 0,
        prestige: 0,
        notoriety: 0,
        sourceId: x.sourceId,
        custom: false,
        notes: '',
      })),
    equipment: [],
    value: 0,
    load: { current: 0, burdened: 4, maximum: 8 },
    harm: {
      depletion: 0,
      depletionMaximum: 4,
      exhaustion: 0,
      exhaustionMaximum: 4,
      injury: 0,
      injuryMaximum: 4,
    },
    job: {
      name: '',
      employer: '',
      objective: '',
      reward: '',
      status: 'none',
      notes: '',
    },
    temporaryEffects: [],
    advancements: [],
    rollHistory: [],
    history: [],
    notes: '',
    totalExperience: 0,
    currentExperience: 0,
    campaign: { kind: 'none', snapshot: null },
  };
}
export function createRootCampaign(
  status: RootCampaign['creation']['status'] = 'draft',
): RootCampaign {
  return {
    schemaVersion: ROOT_SCHEMA_VERSION,
    name: '',
    gm: '',
    bandName: '',
    mode: 'build',
    layout: {
      build: [...campaignGroupIds],
      play: [
        'jobs',
        'travel',
        'clearings',
        'factions',
        'band',
        'clocks',
        'sessions',
        'campaign',
        'records',
      ],
    },
    enabledSources: ['root.core'],
    showUnavailable: false,
    revision: 0,
    creation: {
      status,
      step: 1,
      statBoost: null,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    roster: [],
    clearings: [],
    factions: factions
      .filter((x) => x.sourceId === 'root.core')
      .map((x) => ({
        id: crypto.randomUUID(),
        definitionId: x.id,
        name: x.name,
        position: 0,
        resources: 0,
        reach: 0,
        currentAction: '',
        lastRoll: null,
        notes: '',
        sourceId: x.sourceId,
        page: x.page,
        custom: false,
      })),
    jobs: [],
    travel: {
      from: '',
      to: '',
      route: '',
      leader: '',
      scout: '',
      cook: '',
      rolls: [],
      notes: '',
    },
    clocks: [],
    sessions: [],
    history: [],
    notes: '',
  };
}
