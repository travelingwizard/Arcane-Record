import { actions, chosen, items } from './catalog';
import {
  BOB_SCHEMA_VERSION,
  characterGroupIds,
  chosenGroupIds,
  legionGroupIds,
} from './definitions';
import type { BobCharacter, BobChosen, BobLegion } from './schema';
const citation = (name: string, kind: string, page: number) => ({
  definitionId: `bob.core.${kind}.${name
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')}`,
  name,
  sourceId: 'bob.core',
  page,
  notes: '',
});
export function createBobCharacter(
  status: BobCharacter['creation']['status'] = 'draft',
): BobCharacter {
  return {
    schemaVersion: BOB_SCHEMA_VERSION,
    name: '',
    player: '',
    pronouns: '',
    look: '',
    background: '',
    personality: '',
    playbookId: '',
    heritageId: '',
    heritageName: '',
    heritageTraits: [],
    bonds: '',
    mode: 'build',
    layout: {
      build: [...characterGroupIds],
      play: [
        'stress',
        'harm',
        'mission',
        'actions',
        'abilities',
        'loadout',
        'heritage',
        'character',
        'advancement',
        'records',
      ],
    },
    creation: {
      status,
      step: 1,
      additionalRanks: 0,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    actions: actions.map((x) => ({
      definitionId: x.id,
      name: x.name,
      sourceId: x.sourceId,
      page: x.page,
      notes: x.summary,
      rating: 0,
      mastery: false,
      xp: 0,
    })),
    specialAbilities: [],
    specialistAction: { name: '', uses: 0, maximum: 0 },
    stress: { current: 0, maximum: 6 },
    trauma: [],
    harm: [],
    armor: { normal: false, heavy: false, special: false },
    corruption: 0,
    blights: [],
    load: 'normal',
    items: items.slice(0, 5).map((x) => ({
      definitionId: x.id,
      name: x.name,
      sourceId: x.sourceId,
      page: x.page,
      notes: x.summary,
      load: 1,
      uses: 0,
      maximumUses: 0,
      equipped: false,
      state: 'ready',
    })),
    mission: { title: '', role: '', objective: '', notes: '' },
    xp: { playbook: 0, insight: 0, prowess: 0, resolve: 0 },
    history: [],
    rollHistory: [],
    notes: '',
    legion: { kind: 'none' },
  };
}
export function createBobLegion(
  status: BobLegion['creation']['status'] = 'draft',
): BobLegion {
  return {
    schemaVersion: BOB_SCHEMA_VERSION,
    name: 'The Legion',
    gm: '',
    year: 1,
    mode: 'build',
    layout: {
      build: [...legionGroupIds],
      play: [
        'missions',
        'personnel',
        'commander',
        'marshal',
        'quartermaster',
        'spymaster',
        'lorekeeper',
        'campaign',
        'divine',
        'clocks',
        'history',
        'records',
      ],
    },
    revision: 0,
    creation: { status, step: 1, baseline: null, finalizedAt: null },
    chosenId: '',
    chosenRecordId: null,
    brokenId: '',
    location: 'Ettenmark Fields',
    pressure: 0,
    time: 0,
    advance: 0,
    morale: 8,
    supply: 3,
    intel: 0,
    roles: Object.fromEntries(
      ['Commander', 'Marshal', 'Quartermaster', 'Lorekeeper', 'Spymaster'].map(
        (x) => [x, { player: '', abilities: [], notes: '' }],
      ),
    ),
    personnel: [],
    squads: [],
    missions: [],
    materiel: [],
    annals: [],
    fallen: [],
    spies: [],
    clocks: [],
    brokenNotes: '',
    history: [],
    rollHistory: [],
    notes: '',
  };
}
export function createBobChosen(chosenName = 'Shreya'): BobChosen {
  const def = chosen.find((x) => x.name === chosenName) ?? chosen[0]!;
  return {
    schemaVersion: BOB_SCHEMA_VERSION,
    name: def.name,
    chosenId: def.id,
    player: '',
    look: '',
    mode: 'build',
    layout: {
      build: [...chosenGroupIds],
      play: [
        'favor',
        'mission',
        'relationships',
        'identity',
        'advancement',
        'records',
      ],
    },
    favor: 0,
    abilities: [citation('Starting Chosen Ability', 'chosen-ability', 166)],
    relationships: '',
    startingMission: '',
    advancement: [],
    notes: '',
    legion: { kind: 'none' },
  };
}
