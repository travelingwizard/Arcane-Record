import { actions, factions } from './catalog';
import { characterGroupIds, shipGroupIds } from './definitions';
import type { SandvCharacter, SandvShip } from './schema';
const cited = (x: {
  id: string;
  name: string;
  sourceId: string;
  page: number;
}) => ({
  id: crypto.randomUUID(),
  definitionId: x.id,
  name: x.name,
  sourceId: x.sourceId,
  page: x.page,
  notes: '',
  custom: false,
});
export function createSandvCharacter(
  status: SandvCharacter['creation']['status'] = 'draft',
): SandvCharacter {
  return {
    schemaVersion: 1,
    name: '',
    player: '',
    alias: '',
    pronouns: '',
    look: '',
    heritageId: '',
    backgroundId: '',
    playbookId: '',
    mode: 'build',
    layout: {
      build: [...characterGroupIds],
      play: [
        'stress-harm',
        'job',
        'actions',
        'abilities',
        'loadout',
        'vice',
        'downtime',
        'advancement',
        'character',
        'records',
      ],
    },
    creation: {
      status,
      step: 1,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    actions: actions.map((x) => ({ ...cited(x), rating: 0, xp: 0 })),
    abilities: [],
    vice: { typeId: '', purveyor: '', notes: '' },
    friend: '',
    rival: '',
    stress: 0,
    trauma: [],
    harm: [],
    healing: 0,
    armor: { normal: false, heavy: false, special: false },
    load: 'normal',
    items: [],
    cred: 0,
    stash: 0,
    job: {
      plan: '',
      detail: '',
      target: '',
      position: 'risky',
      effect: 'standard',
      notes: '',
    },
    downtime: [],
    projects: [],
    xp: { playbook: 0, insight: 0, prowess: 0, resolve: 0 },
    rollHistory: [],
    history: [],
    notes: '',
    totalExperience: 0,
    currentExperience: 0,
    ship: { kind: 'none' },
  };
}
export function createSandvShip(
  status: SandvShip['creation']['status'] = 'draft',
): SandvShip {
  return {
    schemaVersion: 1,
    name: '',
    gm: '',
    typeId: '',
    callsign: '',
    mode: 'build',
    layout: {
      build: [...shipGroupIds],
      play: [
        'damage',
        'jobs',
        'systems',
        'crew',
        'heat',
        'upgrades',
        'factions',
        'downtime',
        'clocks',
        'ship',
        'records',
      ],
    },
    creation: {
      status,
      step: 1,
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    revision: 0,
    crew: [],
    systems: {
      comms: { rating: 0, damage: 0 },
      engines: { rating: 0, damage: 0 },
      hull: { rating: 0, damage: 0 },
      weapons: { rating: 0, damage: 0 },
    },
    abilities: [],
    upgrades: [],
    gambits: { current: 2, maximum: 2 },
    cred: 2,
    debt: 0,
    heat: 0,
    wanted: 0,
    crewXp: 0,
    jobs: [],
    factions: factions.map((x) => ({
      id: crypto.randomUUID(),
      definitionId: x.id,
      name: x.name,
      tier: 0,
      status: 0,
      atWar: false,
      notes: '',
    })),
    downtime: [],
    clocks: [],
    rollHistory: [],
    history: [],
    notes: '',
  };
}
