  'Torchbearer 2e: Lore Master’s Manual';

const slug = (name: string) =>
  name
    .normalize('NFKD')
    .replace(/[’']/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();

const lore = (
  kind: TorchbearerReferenceDefinition['kind'],
  name: string,
  category: string,
  page: number,
  mechanics: string,
  requirements: string[] = [],
): TorchbearerReferenceDefinition => ({
  id: `tb2.lore-master.${kind}.${slug(name)}`,
  kind,
  name,
  category,
  summary: mechanics,
  creationHint: mechanics,
  mechanics,
  requirements,
  aliases: [],
  sourceId: TORCHBEARER_LORE_MASTER_SOURCE_ID,
  source: TORCHBEARER_LORE_MASTER_SOURCE,
  page,
});

const coreSkill = (name: string) => `tb2.core.skill.${slug(name)}`;
const coreWeapon = (name: string) => `tb2.core.weapon.${slug(name)}`;
const loreTrait = (name: string) => `tb2.lore-master.trait.${slug(name)}`;

