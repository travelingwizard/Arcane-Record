const classEntry = (
  classId: 'shaman' | 'skald' | 'thief',
  page: number,
  skills: Record<string, number>,
  trait: string,
  weapons: string[],
  details: Partial<TorchbearerClassDefinition>,
): TorchbearerClassDefinition => ({
  ...lore(
    'class',
    classId[0]!.toUpperCase() + classId.slice(1),
    'human',
    page,
    `A human ${classId} with distinct training, equipment permissions, and level benefits from the Lore Master’s Manual.`,
  ),
  classId,
  stockId: 'human',
  fixedWill: null,
  fixedHealth: null,
  skillRatings: skills,
  traitId: loreTrait(trait),
  allowedWeaponIds: weapons,
  forbiddenWeaponIds: [],
  startingArmorId: null,
  mayTakeShield: false,
  mayTakeHelmet: false,
  requiresMentor: false,
  startingMemoryPalace: 0,
  startingUrdr: 0,
  ...details,
});

