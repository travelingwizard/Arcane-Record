import { coc7eSkills } from './catalog';
import { COC7E_SCHEMA_VERSION, coc7eGroupIds } from './definitions';
import type { Coc7eInvestigator } from './schema';
const recordSkill = (x: (typeof coc7eSkills)[number]) => ({
  id: crypto.randomUUID(),
  definitionId: x.id,
  name: x.name,
  sourceId: 'coc7e.investigators-handbook',
  page: x.page,
  notes: '',
  custom: false,
  rating: x.base,
  baseChance: x.base,
  occupationPoints: 0,
  personalPoints: 0,
  experienceChecked: false,
  training: false,
  specialty: '',
  family: x.family,
  origin: 'catalog' as const,
});
export function createCoc7eInvestigator(
  status: Coc7eInvestigator['creation']['status'] = 'draft',
  method: Coc7eInvestigator['creation']['method'] = 'standard',
): Coc7eInvestigator {
  const quick = method === 'quick-fire';
  return {
    schemaVersion: COC7E_SCHEMA_VERSION,
    name: '',
    player: '',
    pronouns: '',
    age: 25,
    birthplace: '',
    residence: '',
    era: '1920s',
    campaignPremise: '',
    concept: '',
    occupationName: '',
    mode: 'build',
    layout: {
      build: [...coc7eGroupIds],
      play: [
        'investigation',
        'resources',
        'skills',
        'combat',
        'equipment',
        'characteristics',
        'backstory',
        'development',
        'investigator',
        'records',
      ],
    },
    enabledSources: ['coc7e.investigators-handbook'],
    creation: {
      status,
      method,
      step: 1,
      occupationId: '',
      occupationPointsSpent: 0,
      personalPointsSpent: 0,
      ageDeductions: { physical: 0, education: 0, appearance: 0, movement: 0 },
      eduChecks: [],
      rolls: [],
      experiencePackageId: '',
      experienceSanLoss: 0,
      experienceSkillPoints: 0,
      optionalRules: {
        startingSkillCap: false,
        skillCap: 75,
        transferableSpecializations: false,
        humanPotential: false,
      },
      approvals: [],
      baseline: null,
      rebuildDraft: null,
      finalizedAt: null,
    },
    characteristics: quick
      ? {
          str: 40,
          con: 50,
          dex: 50,
          app: 50,
          pow: 60,
          siz: 60,
          int: 70,
          edu: 80,
        }
      : { str: 0, con: 0, dex: 0, app: 0, pow: 0, siz: 0, int: 0, edu: 0 },
    resources: {
      luckCurrent: 0,
      luckMaximum: 0,
      sanityCurrent: 0,
      sanityMaximum: 99,
      magicPointsCurrent: 0,
      hitPointsCurrent: 0,
      dailySanityStart: 0,
      dailySanityLoss: 0,
      temporaryInsanity: false,
      indefiniteInsanity: false,
      boutActive: false,
    },
    skills: coc7eSkills.map(recordSkill),
    creditRating: 0,
    spendingLevel: '',
    cash: '',
    assets: '',
    backstory: {
      personalDescription: '',
      ideology: '',
      significantPeople: '',
      meaningfulLocations: '',
      treasuredPossessions: '',
      traits: '',
      keyConnection: '',
    },
    organizations: [],
    contacts: [],
    phobiasManias: [],
    injuries: [],
    clues: [],
    mythosRecords: [],
    equipment: [],
    spells: [],
    weapons: [],
    temporaryEffects: [],
    notes: '',
    totalExperience: 0,
    currentExperience: 0,
    rollHistory: [],
    rollerSettings: { historyMode: 'bounded', historyLimit: 10 },
    history: [],
  };
}
